# Deskripsi : Trailing stop saham

# Kamus
# persen     : % trailing stop yang digunakan
# harga_beli : harga saham saat dibeli pada hari pertama
# puncak     : harga saham tertinggi yang pernah dicapai
# batas_jual : batas harga jual berdasarkan trailing stop
# hari       : nomor hari pengamatan harga saham
# harga      : harga saham pada hari yang sedang diamati
# hasil      : selisih harga jual dan harga beli

persen = float(input("Masukkan persentase trailing stop: "))
harga_beli = int(input("Masukkan harga saham hari ke -1: "))

puncak = harga_beli
batas_jual = puncak * (1 - persen / 100)
hari = 1
harga = harga_beli

while harga > batas_jual:
  hari = hari + 1
  harga = int(input("Masukkan harga saham hari ke -" + str(hari) + ": "))

  if harga > puncak:
    puncak = harga
    batas_jual = puncak * (1 - persen / 100)

print("Trailing stop ter-trigger pada hari ke -" + str(hari), "dengan harga Rp", harga, ".")
print("Harga puncak : Rp", puncak, ".")
print("Batas jual (trailing stop", persen, "%): Rp", batas_jual, ".")

hasil = harga - harga_beli

if hasil > 0:
  print("Keuntungan : Rp", hasil, ".")
elif hasil < 0:
  print("Kerugian : Rp", -hasil, ".")
else:
  print("Tidak ada untung dan tidak ada rugi.")
# mengambil input awal
saldo = int(input("Masukan saldo awal (Rp): "))
n = int(input("Masukan jumlah transaksi (N): "))

# Variabel pembantu
total_pengeluaran = 0
total_pemasukan = 0
transaksi_negatif_pertama = 0

# Mulai perhitungan
for i in range(1, n + i):
    nilai = int(input(f"Masukan nilai transaksi ke-{i} (Rp): "))

    # Saldo saat ini
    Saldo = saldo + nilai
    print(f"Saldo saat transaksi ke-{i}: Rp.{Saldo}.")

    # Total pemasukan dan pengeluaran
    if nilai > 0:
          total_pemasukan = total_pemasukan + nilai
    elif nilai < 0:
          total_pengeluaran = total_pengeluaran + nilai

    # Apakah nilai ini membuat saldo pertama negatif?
    if saldo < 0 and transaksi_negatif_pertama == 0:
          transaksi_negatif_pertama = i

# Menampilkan hasil
if transaksi_negatif_pertama > 0:
    print(f"Saldo tuan Mik pertama kali negatif pada transaksi ke-{transaksi_negatif_pertama}.")
else:
    print("Saldo tuan Mik tidak pernah negatif selama (n) transaksi.")

print(f"Total pemasukan : Rp{total_pemasukan}. Total pengeluaran : Rp{total_pengeluaran}")
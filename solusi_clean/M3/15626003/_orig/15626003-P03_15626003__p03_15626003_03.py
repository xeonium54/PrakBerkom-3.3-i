# Masukan input
n = int(input("Masukan panjang kebun: "))
input_tanah = input("Masukan array tinggi tanah: ").split()

# Mengubah teks input menjadi angka di list (array)
tanah =[]
for x in input_tanah:
    tanah.append(int(x))

w = int(input("Masukan batas toleransi air: "))

total_air = 0

# Perulangan dari indeks n-2 (Mengabaikan ujung paling kiri dan kanan)
for i in range(1, n - 1):

    # Cari manual dinding tertinggi di sebelah KIRI indeks i
    max_kiri = tanah[0]
    for j in range(i):
        if tanah[j] > max_kiri:
            max_kiri = tanah[j]

    # Cari manual dinding tertinggi di sebelah KANAN indeks i
    max_kanan = tanah[i + 1]
    for j in range(i + 2, n):
        if tanah[j] > max_kanan:
            max_kanan = tanah[j]

    # Cari dinding mana yang lebih pendek (Pengganti fungsi min())
    if max_kiri < max_kanan:
        batas_air = max_kiri
    else:
        batas_air = max_kanan

    # Jika batas air lebih tinggi dari tanah, hitung genangan nya
    if batas_air > tanah[i]:
        total_air = total_air + (batas_air - tanah[i])

# Mencetak hasil akhir dan bagaimana nasib kaktus
print(f"Total volume genangan air adalah {total_air}. ")

if total_air > w:
    print("Kaktus Tuan Ky mati membusuk!.")
else:
    print("Kaktus Tuan Ky Selamat!. ")
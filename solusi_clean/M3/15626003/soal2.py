# Input persentase trailing stop
persen = float(input("Masukan persentase trailing stop: "))

# Setup hari pertama (Beli)
hari = 1
harga_sekarang = float(input(f"Masukan harga saham hari ke-{hari}: "))
harga_beli = harga_sekarang
puncak = harga_sekarang

# Rumus batas jual awal
batas_jual = puncak * (1 - (persen / 100))

# Perulangan terus berjalan selama harga masih di atas batas jual
while harga_sekarang > batas_jual:
    hari = hari + 1
    harga_sekarang = float(input(f"Masukan harga saham hari ke-{hari}: "))
    if harga_sekarang > puncak:
        puncak = harga_sekarang
        batas_jual = puncak * (1 - (persen / 100))

# Mencetak hasil dari perulangan (sudah ter-trigger)
print(f"Trailing stop ter-trigger pada hari ke-{hari}dengan harga Rp{int(harga_sekarang)}.")
print(f"Harga puncak: Rp{int(puncak)}.")
print(f"Batas jual (Trailing stop {persen}%): Rp{batas_jual}")

# Hitung untung atau rugi
selisih = harga_sekarang - harga_beli
if selisih >= 0:
    print(f"Untung sebesar Rp{int(selisih)}.")
else:
    print(f"Rugi sebesar Rp{int(-selisih)}.")
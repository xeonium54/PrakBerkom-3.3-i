saldo_awal = int(input("Masukkan saldo awal (Rp): "))
n = int(input("Masukkan jumlah transaksi (N): "))


transaksi = []


for i in range(n):
    nilai = int(input(f"Masukkan nilai transaksi ke-{i+1}: "))
    transaksi.append(nilai)


saldo_sekarang = saldo_awal
total_pemasukan = 0
total_pengeluaran = 0
transaksi_negatif_pertama = 0

riwayat_saldo = []


for i in range(n):
    t = transaksi[i]
    saldo_sekarang += t
    riwayat_saldo.append(saldo_sekarang)


    if t > 0:
        total_pemasukan += t
    elif t < 0:
        total_pengeluaran += t


    if saldo_sekarang < 0 and transaksi_negatif_pertama == 0:
        transaksi_negatif_pertama = i + 1

#  OUTPUT


for i in range(n):
    print(f"Saldo setelah transaksi ke-{i+1}: Rp{riwayat_saldo[i]}.")


if transaksi_negatif_pertama > 0:
    print(f"Saldo Tuan Mik pertama kali negatif pada transaksi ke-{transaksi_negatif_pertama}.")
else:
    print(f"Saldo Tuan Mik tidak pernah negatif selama {n} transaksi.")


print(f"Total pemasukan: Rp{total_pemasukan}. Total pengeluaran: Rp{total_pengeluaran}.")


persen = float(input("Masukkan persentase trailing stop: "))

# Harga hari pertama adalah harga beli sekaligus harga puncak awal
harga_beli = float(input("Masukkan harga saham hari ke -1: "))
puncak = harga_beli
hari = 1

while True:
    hari = hari + 1
    harga = float(input("Masukkan harga saham hari ke -" + str(hari) + ": "))

    # Perbarui harga puncak jika ada rekor baru
    if harga > puncak:
        puncak = harga

    # Hitung batas jual dari harga puncak terbaru
    batas_jual = puncak * (1 - persen / 100)

    # Periksa apakah trailing stop terpicu
    if harga <= batas_jual:
        print("Trailing stop ter - trigger pada hari ke -", hari,
              "dengan harga Rp", harga, ".")
        print("Harga puncak : Rp", puncak, ".")
        print("Batas jual (trailing stop", persen, "%): Rp", batas_jual, ".")

        hasil = harga - harga_beli

        if hasil > 0:
            print("Keuntungan : Rp", hasil, ".")
        elif hasil < 0:
            print("Kerugian : Rp", -hasil, ".")
        else:
            print("Tidak untung dan tidak rugi.")

        break

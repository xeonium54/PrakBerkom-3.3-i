# Deskripsi : Memantau saldo transaksi e-wallet

saldo = int(input("Masukkan saldo awal (Rp): "))
N = int(input("Masukkan jumlah transaksi  (N): "))

total_pemasukkan = 0
total_pengeluaran = 0
transaksi_negatif = 0

for i in range(1, N + 1):
  nilai = int(input("Masukkan nilai transaksi ke -" + str(i) + ": "))

  # Perbarui saldo setelah transaksi
  saldo = saldo + nilai

  # Hitung pemasukkan dan pengeluaran
  if nilai > 0:
    total_pemasukkan = total_pemasukkan + nilai
  elif nilai < 0:
    total_pengeluaran = total_pengeluaran + nilai

  # Catat transaksi pertama saat saldo negatif
  if saldo < 0 and transaksi_negatif == 0:
    transaksi_negatif = i

  print("Saldo setelah transaksi ke -" + str(i) + ": Rp", saldo, ".")

# Periksa apakah saldo pernah negatif
if transaksi_negatif != 0:
  print("Saldo Tuam Mik pertama kali negatif pada transaksi ke -", transaksi_negatif, ".")
else:
  print("Saldo Tuan Mik tidak pernah negatif selama", N, "transaksi.")

print("Total pemasukkan : Rp",total_pemasukkan,
      ". Total pengeluaran : Rp", total_pengeluaran, ".")


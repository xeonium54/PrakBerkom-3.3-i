# Deskripsi: Menghitung volume genangan air di kebun

N = int(input("Masukkan panjang kebun: "))
H = list(map(int, input("Masukkan array ketinggian tanah: ").split()))
W = int(input("Masukkan batas toleransi air: "))

total_air = 0

# Titik pertama dan terakhir tidak dapat menampung air
for i in range(1, N - 1):

    # Cari tanah tertinggi di sebelah kiri titik i
    kiri = H[0]
    for j in range(1, i):
        if H[j] > kiri:
            kiri = H[j]

    # Cari tanah tertinggi di sebelah kanan titik i
    kanan = H[i + 1]
    for j in range(i + 2, N):
        if H[j] > kanan:
            kanan = H[j]

    # Tentukan dinding yang lebih pendek
    if kiri < kanan:
        batas_air = kiri
    else:
        batas_air = kanan

    # Hitung air hanya jika batas air lebih tinggi dari tanah
    if batas_air > H[i]:
        total_air = total_air + (batas_air - H[i])

print("Total volume genangan air adalah", total_air, ".")

if total_air > W:
    print("Kaktus Tuan Ky mati membusuk!")
else:
    print("Kaktus Tuan Ky selamat!")


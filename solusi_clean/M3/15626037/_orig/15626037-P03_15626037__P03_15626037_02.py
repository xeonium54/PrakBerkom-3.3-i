persen = float(input("Masukkan persentase trailing stop: "))

harga_beli = float(input("Masukkan harga saham hari ke-1: "))
puncak = harga_beli
batas_jual = puncak * (1-persen/100)

hari = 1
harga_sekarang = harga_beli

while harga_sekarang > batas_jual:
  hari += 1
  harga_sekarang = float(input(f"Masukkan harga saham hari ke-{hari}: "))

  if harga_sekarang > puncak:
    puncak = harga_sekarang
    batas_jual = puncak * (1-persen/100)

harga_jual_str = str(int(harga_sekarang)) if harga_sekarang.is_integer() else str(harga_sekarang)
puncak_str =  str(int(puncak)) if puncak.is_integer() else str(puncak)
persen_str = str(int(persen)) if persen.is_integer() else str(persen)

print(f"Trailing stop ter -trigger pada hari ke -{hari} dengan harga Rp{harga_jual_str}.")
print(f"Harga puncak : Rp{puncak_str}")
print(f"Batas jual (trailing stop {persen}): Rp{batas_jual}.")

selisih = harga_sekarang - harga_beli

if selisih >= 0:
  print(f"Keuntungan: Rp{selisih}.")
else:
  print(f"Kerugian: Rp{selisih}.")
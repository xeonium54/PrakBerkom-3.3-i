S_awal = int(input("Masukkan saldo awal (Rp): "))
N = int(input("Masukkan jumlah transaksi (N): "))

S_sekarang = S_awal
T_pemasukan = 0
T_pengeluaran = 0

t_negatif_pertama = -1

for i in range(1, N+1):
  nilai = int(input(f"Masukkan nilai transaksi ke-{i}: "))

  S_sekarang += nilai
  print(f"Saldo setelah transaksi ke-{i}: Rp{S_sekarang}.")

  if S_sekarang < 0 and t_negatif_pertama == 1:
    t_negatif_pertama = i

  if nilai > 0:
    T_pemasukan += nilai
  else:
    T_pengeluaran += nilai

if t_negatif_pertama == -1:
  print(f"Saldo Tuan Mik pertama kali negatif pada transaksi ke-{t_negatif_pertama}.")
else:
  print(f"Saldo tuan Mik tidak pernah negatif selama {N} transaksi.")

print(f"Total pemasukkan: {T_pemasukan}. Total pengeluaran: {T_pengeluaran}.")


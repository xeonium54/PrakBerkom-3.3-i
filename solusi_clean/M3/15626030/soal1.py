saldo_awal = float(input("masukkan saldo awal: "))
jumlah_transaksi = int(input("masukkan jumlah transaksi: "))

pemasukan = 0
pengeluaran = 0
saldo_terakhir = saldo_awal

for i in range(jumlah_transaksi):
    nilai_transaksi = float(input("masukkan nilai transaksi: "))

    saldo_setelah_transaksi_ke_i = saldo_terakhir + nilai_transaksi
    print(f"saldo setelah transaksi ke-{i+1}: {saldo_setelah_transaksi_ke_i}")
    saldo_terakhir += nilai_transaksi
    if saldo_terakhir < 0:
        print("saldo pertama kali menjadi negatif pada transaksi ke-", i+1)
        break
    if nilai_transaksi > 0:
        pemasukan += nilai_transaksi
        print(f"pemasukan: {pemasukan}")
    else:
        pengeluaran += nilai_transaksi
        print(f"pengeluaran: {pengeluaran}")

print(f"total pemasukan: {pemasukan}")
print(f"total pengeluaran: {pengeluaran}")


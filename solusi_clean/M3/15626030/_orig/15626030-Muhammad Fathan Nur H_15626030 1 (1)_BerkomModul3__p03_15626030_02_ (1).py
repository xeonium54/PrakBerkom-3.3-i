Persentase_trailing_stop = float(input("Masukkan Persentase trailing stop: "))
Jumlahhari = int(input("Masukkan Jumlah hari: "))

Puncak = 0


for i in range(Jumlahhari):
    Harga = float(input("Masukkan harga saham hari ke-" + str(i+1) + ": "))
    Puncakke = max(Puncak, Harga)
    Batasjual = Puncakke * (1 - Persentase_trailing_stop/100)
    if Harga > Batasjual:
      Puncakke = Harga
      print(f"Ada puncak baru")
    elif Harga < Batasjual:
      print(f"Trailing stop ter trigger pada hari ke {str(i+1)}")

      Harga_Puncak = Puncakke
      print(f"Harga Puncak adalah {Harga_Puncak}")

      Batas_Jual = Harga_Puncak * (1 - Persentase_trailing_stop/100)
      print(f"Batas Jual adalah {Batas_Jual}")

      Keuntungan = Harga - Harga_Puncak
      print(f"Keuntungan adalah {Keuntungan}")
      break
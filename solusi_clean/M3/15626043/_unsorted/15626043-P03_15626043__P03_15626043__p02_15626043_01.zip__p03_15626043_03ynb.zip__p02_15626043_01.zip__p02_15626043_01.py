S = int(input('Masukkan saldo awal (Rp) : '))
N = int(input('Masukkan jumlah transaksi (N) : '))
Pemasukan = 0
Pengeluaran = 0
Negatif = False
Transaksi_Negatif = 0
T  = [0 for i in range(0, N)]
for i in range (0,N):
  T[i] = int(input('Masukkan nilai transaksi ke- '+str(i+1)+':'))
  S = S + T[i]
  print('Saldo setelah transaksi ke-'+str(i+1)+':', S)
  if T[i]>0:
    Pemasukan = Pemasukan + T[i]
  else:
    Pengeluaran = Pengeluaran + T[i]
  if S<0 and Negatif == False:
    Negatif = True
    Transaksi_Negatif = i+1
if Negatif == True:
  print('Saldo Tuan Mik pertama kali negatif pada transaksi ke-'+str(Transaksi_Negatif)+':')
else:
  print('Saldo Tuan Mik tidak pernah negatif selama', N, 'transaksi')
print('Total Pemasukan', Pemasukan)
print('Total Pengeluaran', Pengeluaran)
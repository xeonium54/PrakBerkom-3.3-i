# Deskripsi : Mengetahui Transaksi Tuan MIK




#Input Saldo Awal
SaldoAwal = int(input("Masukkan Saldo Awal:"))
n = int(input("Masukkan Jumlah Transaksi (n):"))


saldo = SaldoAwal
transaksi = []
pemasukkan = 0
pengeluaran = 0
negatif_ke = None

for i in range(1, n + 1):
    Transaksi = int(input(f"Masukkan nilai transaksi ke -{i}: "))
    transaksi.append(Transaksi)
    if Transaksi > 0:
        pemasukkan += Transaksi
    else:
        pengeluaran += Transaksi

#Output
for i, t in enumerate(transaksi, 1):
    saldo += t
    if saldo < 0:
        print(f"Saldo setelah transaksi ke -{i}: Rp -{abs(saldo)}.")
    else:
        print(f"Saldo setelah transaksi ke -{i}: Rp{saldo} .")

    if saldo < 0 and negatif_ke is None:
        negatif_ke = i


if negatif_ke is not None:
    print("Saldo Tuan Mik pertama kali negatif pada transaksi ke", (negatif_ke) )
else:
    print("Saldo Tuan Mik tidak pernah negatif.")

print("Total pemasukan : Rp", (pemasukkan))
print("Total pengeluaran : Rp", (pengeluaran))


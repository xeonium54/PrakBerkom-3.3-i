batas_shift = int(input("Masukkan batas shift normal (Menit):"))
U = int(input("Masukkan upah per menit:"))
P = float(input("Masukkan pengali upah lembur:"))
T = int(input("Masukkan tunjangan makan:"))
batas_tunjangan = int(input("Masukkan batas tunjangan makan (Menit):"))

#Penyelesaian Matematikanya:

Total_durasi_kerja = (j2 - j1) * 60 + (m2 - m1)
jam_kerja = Total_durasi_kerja // 60
menit_kerja = Total_durasi_kerja % 60


Menit_kerja_lembur = Total_durasi_kerja - batas_shift
Menit_kerja_normal = Total_durasi_kerja - Menit_kerja_lembur

Total_durasi_kerja <= batas_shift == Menit_kerja_normal
Total_durasi_kerja > batas_shift == Menit_kerja_lembur

Tunjangan_makan = T

Total_upah = (batas_shift * U) +  (Menit_kerja_lembur * U * P) + (Tunjangan_makan)

#Memunculkan Data
print("Total durasi kerja:", jam_kerja, "jam", menit_kerja, "menit")
print("Menit kerja normal:", Menit_kerja_normal, "menit")

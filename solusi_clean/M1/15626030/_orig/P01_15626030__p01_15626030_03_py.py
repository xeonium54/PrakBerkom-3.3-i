#Program Tunjangan Tuan Joji

j1 = int(input("jam masuk"))
m1 = int(input("menit masuk"))
j2 = int(input("jam keluar"))
m2 = int(input("menit keluar"))
N = int(input("batas shift normal"))
u = float(input("upah per menit"))
l = float(input("pengali upah lembur"))
M = float(input("tunjangan makan"))
Tmin = int(input("batas minimal tunjangan"))

#Menghitung Total Durasi Kerja
total_durasi_kerja = (j2 * 60 * m2) - (j1 * 60 + m1)

#Menghitung Menit Lembur
menit_lembur = (total_durasi_kerja - N) * 1

#Total Upah
total_upah = (N * u) + (menit_lembur * l) + (M)



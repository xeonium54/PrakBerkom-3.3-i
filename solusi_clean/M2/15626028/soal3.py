jenis_A = input("Masukkan jenis Kereta A (Eksekutif/Bisnis/Kargo): ")
D_A = int(input("Masukkan jarak Kereta A (m): "))
V_A = int(input("Masukkan kecepatan Kereta A (m/s): "))


jenis_B = input("Masukkan jenis Kereta B (Eksekutif/Bisnis/Kargo): ")
D_B = int(input("Masukkan jarak Kereta B (m): "))
V_B = int(input("Masukkan kecepatan Kereta B (m/s): "))


T_A = D_A / V_A
T_B = D_B / V_B


selisih = T_A - T_B
if selisih < 0:
    selisih = -selisih


if selisih >= 30.0:
    if T_A < T_B:
        print("Jalur aman. Kereta A melintas duluan tanpa henti.")
    else:
        print("Jalur aman. Kereta B melintas duluan tanpa henti.")


else:
    print("Konflik terdeteksi!", end=" ")


    prio_A = 3 if jenis_A == "Eksekutif" else (2 if jenis_A == "Bisnis" else 1)
    prio_B = 3 if jenis_B == "Eksekutif" else (2 if jenis_B == "Bisnis" else 1)

    kereta_prioritas = ""


    if prio_A != prio_B:
        if prio_A > prio_B:
            kereta_prioritas = "A"
        else:
            kereta_prioritas = "B"
    else:
        # Jika jenis kereta sama, bandingkan waktu tiba
        if T_A != T_B:
            if T_A < T_B:
                kereta_prioritas = "A"
            else:
                kereta_prioritas = "B"
        else:
            # Jika waktu tiba sama, bandingkan jarak
            if D_A != D_B:
                if D_A < D_B:
                    kereta_prioritas = "A"
                else:
                    kereta_prioritas = "B"
            else:
                # Jika jarak juga sama, Kereta A diprioritaskan (jalur utama)
                kereta_prioritas = "A"

    # Menampilkan hasil prioritas melintas dan menghitung waktu tunggu
    print(f"Kereta {kereta_prioritas} diprioritaskan melintas.")

    if kereta_prioritas == "A":
        waktu_tunggu = (T_A + 40.0) - T_B
        print(f"Kereta B harus berhenti dan menunggu selama {waktu_tunggu:.1f} detik.")
    else:
        waktu_tunggu = (T_B + 40.0) - T_A
        print(f"Kereta A harus berhenti dan menunggu selama {waktu_tunggu:.1f} detik.")
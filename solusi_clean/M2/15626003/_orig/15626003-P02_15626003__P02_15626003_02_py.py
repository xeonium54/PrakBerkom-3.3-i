# Masukan Input
durasi = int(input("Masukkan durasi parkir (jam): "))
is_mobil_listrik = input("Apakah parkir mobil listrik? (y/n): ")
is_akhir_pekan = input("Apakah parkir di akhir pekan? (y/n): ")

# Menghitung tarif berdasarkan durasi
if durasi <= 2:
  tarif_dasar = 5000
elif durasi <= 6:
  tarif_dasar = 5000 + (durasi - 2) * 3000
else:
  tarif_dasar = 5000 + (4 * 3000) + (durasi - 6) * 2000

# Aturan tambahan : potongan untuk mobil listrik (jika durasi hanya , 2 jam)
if is_mobil_listrik == 'y' and durasi <= 2:
  tarif_dasar -= 5000

# Aturan tambahan : Pengali tarif akhir pekan
if is_akhir_pekan == 'y':
  total_tarif = tarif_dasar * 1,2
else:
  total_tarif = float(tarif_dasar)

# Menampilkan hasil akhir (menggunakan int jika nilainya bulat)
if total_tarif.is_integer():
  print(f"Total tarif parkir adalah Rp{(total_tarif)}")
else:
  print(f"Total tarif parkir adalah Rp{(total_tarif)}")
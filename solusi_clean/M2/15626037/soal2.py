P = int(input("Masukkan durasi parkir (jam): "))
J = (input("Apakah mobil listrik? (y/n)): "))
M = (input("Apakah akhir pekan? (y/n)): "))
Tf = 0

if P <= 2:
  Tf = 5000
elif 2 < P <= 6:
  Tf = 5000 + (P-2) * 3000
elif P > 6:
  Tf = 5000 + (4*3000) + (P-6) * 2000


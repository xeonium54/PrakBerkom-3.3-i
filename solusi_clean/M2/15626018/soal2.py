durasi = float(input("Masukkan durasi parkir (jam): "))
listrik = input("Apakah mobil listrik? (y/n): ")
weekend = input("Apakah akhir pekan? (y/n): ")

if durasi <= 2:
  tarif = 5000
elif durasi <= 6:
  tarif = 5000 + (durasi - 2) * 3000
else:
  tarif = 5000 + 4 * 3000 + (durasi - 6) * 2000

if listrik == "y" and durasi > 2:
  tarif = tarif - 5000

if weekend == "y":
  tarif = tarif * 1.2

if tarif == int(tarif):
  tarif = int(tarif)

print("Total tarif parkir adalah Rp" + str(tarif))
# Deskripsi:Menghitung tarif parkir berdasarkan durasi, jenis kendaraan, dan hari parkir

# Meminta masukan dari pengguna
durasi = float(input("Masukan durasi parkir (jam): "))
listrik = input("Apakah mobil listrik? (y/n): ")
akhir_pekan = input("Apakah akhir pekan? (y/n): ")

# Menghitung tarif dasar berdasarkan durasi parkir
if durasi <= 2:
  tarif = 5000
elif durasi <= 6:
  tarif = 5000 + (durasi - 2) * 3000
else:
  tarif = 5000 + 4 * 3000 + (durasi -6) * 2000

# Memberikan potongan untuk mobil listrik
if listrik == "y" and durasi > 2:
  tarif = tarif - 5000

# Menambahkan tarif akhir pekan
if akhir_pekan == "y":
  tarif = tarif * 1.2

# Menampilkan total tarif
print("Total tarif parkir adalah Rp", tarif)


# Deskripsi : menghitung tarif parkir dasar ditentukan oleh lama durasi parkir dalam jam

durasi_parkir = int(input("masukan lama parkir (jam)"))
mobil_listrik = str(input("mobil listrik (y/n)"))
akhir_pekan = str(input("akhir pekan (y/n)"))

if durasi_parkir <= 2:
  print("tarif parkir adalah Rp 5000")
elif durasi_parkir >= 2 and durasi_parkir <=4:
  print("tarif parkir adalah Rp 8000")
elif durasi_parkir >= 6 :
  print("tarif parkir adaalah Rp 10000")
elif mobil_listrik == "y" :
  print("tarif parkir adalah 3000/5000")
elif akhir_pekan == "y" :
  print("tarif parkir adalah 6000/9600/12000")
else:
  print("tidak dilakukan apa apa")
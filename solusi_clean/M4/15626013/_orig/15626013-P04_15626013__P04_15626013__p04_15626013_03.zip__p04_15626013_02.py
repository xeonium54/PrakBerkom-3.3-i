# Subprogram untuk menghitung skor PIN
def hitung_skor(pin):
    skor = 0
    digit_berbeda = ""

    # Menghitung digit yang berbeda
    for karakter in pin:
        if karakter >= "0" and karakter <= "9":
            if karakter not in digit_berbeda:
                digit_berbeda = digit_berbeda + karakter

    skor = skor + len(digit_berbeda) * 4

    # Memeriksa apakah terdapat huruf besar
    huruf_besar = False

    for karakter in pin:
        if karakter >= "A" and karakter <= "Z":
            huruf_besar = True

    if huruf_besar:
        skor = skor + 10

    # Menghitung poin berdasarkan panjang PIN
    if len(pin) >= 8:
        skor = skor + 15
    elif len(pin) >= 6:
        skor = skor + 5

    # Menghitung penalti digit berurutan
    for i in range(len(pin) - 1):
        if (pin[i] >= "0" and pin[i] <= "9" and
            pin[i + 1] >= "0" and pin[i + 1] <= "9"):

            angka1 = int(pin[i])
            angka2 = int(pin[i + 1])

            if angka1 - angka2 == 1 or angka2 - angka1 == 1:
                skor = skor - 5

    return skor


# Subprogram untuk menentukan kategori PIN
def tentukan_kategori(skor):
    if skor >= 40:
        return "Kuat"
    elif skor >= 20:
        return "Sedang"
    else:
        return "Lemah"


# Program utama
N = int(input("Masukkan jumlah kandidat PIN (N): "))

kuat = 0
sedang = 0
lemah = 0

for i in range(N):
    pin = input("Kandidat PIN ke -" + str(i + 1) + ": ")

    skor = hitung_skor(pin)
    kategori = tentukan_kategori(skor)

    print("PIN ke -" + str(i + 1), "skornya", skor,
          ", tergolong", kategori + ".")

    # Menghitung jumlah setiap kategori
    if kategori == "Kuat":
        kuat = kuat + 1
    elif kategori == "Sedang":
        sedang = sedang + 1
    else:
        lemah = lemah + 1

print("Rekap : Kuat", kuat, ", Sedang", sedang,
      ", Lemah", lemah)


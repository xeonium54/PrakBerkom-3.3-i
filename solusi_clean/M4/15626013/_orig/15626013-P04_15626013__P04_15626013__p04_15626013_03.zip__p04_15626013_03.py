# Subprogram untuk tindakan belajar
def belajar(total, modul, durasi, waktu, energi):

    # Durasi belajar dibatasi oleh sisa waktu
    if durasi > waktu:
        durasi = waktu

    # Durasi belajar dibatasi oleh sisa energi
    batas_energi = energi / 5

    if durasi > batas_energi:
        durasi = batas_energi

    # Menambahkan total belajar pada modul yang dipilih
    total[modul - 1] = total[modul - 1] + durasi

    # Mengurangi waktu dan energi
    waktu = waktu - durasi
    energi = energi - (durasi * 5)

    if energi < 0:
        energi = 0

    return total, waktu, energi


# Subprogram untuk tindakan tidur
def tidur(waktu, energi):

    # Energi bertambah selama tidur
    energi = energi + (waktu * 12.5)

    # Energi maksimal adalah 100
    if energi > 100:
        energi = 100

    # Tidur menggunakan seluruh sisa waktu
    waktu = 0

    return waktu, energi


# Subprogram untuk menghitung prediksi nilai
def hitung_nilai(total, minimum, energi):

    jumlah = 0

    for i in range(4):

        # Membatasi waktu belajar sesuai waktu minimal modul
        if total[i] > minimum[i]:
            durasi = minimum[i]
        else:
            durasi = total[i]

        jumlah = jumlah + (durasi / minimum[i])

    # Menghitung rata-rata penguasaan modul
    rata_rata = jumlah / 4

    # Menghitung faktor
    faktor_energi = (100 ** 2 - (100 - energi) ** 2) / 100

    # Menghitung nilai akhir
    nilai = rata_rata * faktor_energi

    return nilai



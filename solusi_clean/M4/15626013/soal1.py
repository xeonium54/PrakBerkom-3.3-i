# Deskripsi : Menyerdehanakan aspect ratio foto menggunakan FPB

# Subprogram untuk menghitung FPB
def hitung_fpb(a,b):
  while b != 0:
    sisa = a % b
    a = b
    b = sisa
  return a

# Program Utama
lebar = int(input("Masukkan lebar foto ( piksel ): "))
tinggi = int(input("Masukkan tinggi foto ( piksel ): "))

# Menghitung FPB
fpb = hitung_fpb(lebar, tinggi)

# Menyederhanakan ratio
lebar_baru = lebar // fpb
tinggi_baru = tinggi // fpb

print("Aspect ratio disederhanakan menjadi", str(lebar_baru) + ":" + str(tinggi_baru))


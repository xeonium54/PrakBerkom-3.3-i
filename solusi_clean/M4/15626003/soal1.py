def hitung_fpb(a, b):
  while b != 0:
    sisa = a % b
    a = b
    b = sisa
  return a

# Program utama
lebar = int(input("Masukan lebar foto (piksel): "))
tinggi = int(input("Masukan tinggi foto (piksel): "))

fpb = hitung_fpb(lebar, tinggi)
rasio_lebar = lebar // fpb
rasio_tinggi = tinggi // fpb

print(f"Aspek rasio disederhanan menjadi {rasio_lebar}:{rasio_tinggi}")
def tidur(waktu, energi):
    energi += waktu * 12.5
    return 0, (100 if energi > 100 else energi)

def belajar(idx, durasi, T, waktu, energi):
    if durasi > waktu: durasi = waktu
    if durasi > energi / 5: durasi = energi / 5
    T[idx] += durasi
    waktu -= durasi
    energi -= durasi * 5
    if energi <= 0 and waktu > 0:
        print("Tuan Ky terpaksa tidur karena kehabisan energi!")
        return tidur(waktu, 0)
    return waktu, energi

def hitung_nilai(T, t_min, energi):
    rasio = sum((1 if T[i] >= t_min[i] else T[i] / t_min[i]) for i in range(4))
    return (rasio / 4) * ((10000 - (100 - energi)**2) / 100)

# Program Utama
waktu = float(input("Masukkan sisa waktu: "))
t_min = [float(input(f"Masukkan durasi untuk modul ke-{i+1}: ")) for i in range(4)]
T = [0, 0, 0, 0]
energi = 100

while waktu > 0:
    aksi = int(input("1. Belajar\n2. Tidur\nPilih tindakan (1/2): "))
    while aksi != 1 and aksi != 2:
        aksi = int(input("Pilihan tidak tersedia! Pilih tindakan (1/2): "))
    if aksi == 1:
        modul = int(input("Pilih modul yang ingin dipelajari (1-4): "))
        while modul < 1 or modul > 4:
            modul = int(input("Modul tidak tersedia! Pilih modul yang ingin dipelajari (1-4): "))
        durasi = float(input("Masukkan durasi belajar: "))
        waktu, energi = belajar(modul - 1, durasi, T, waktu, energi)
    else:
        waktu, energi = tidur(waktu, energi)

hasil = hitung_nilai(T, t_min, energi)
print(f"Prediksi nilai UAS yang akan didapatkan oleh Tuan Ky adalah {int(hasil) if hasil == int(hasil) else hasil}.")
def hitung_skor(pin):
    skor = 0

    # Digit unik (0-9) -> +4 poin per digit
    for d in "0123456789":
        if d in pin:
            skor += 4

    # Minimal satu huruf besar -> +10 poin
    for h in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        if h in pin:
            skor += 10
            break

    # Panjang PIN
    if len(pin) >= 8:
        skor += 15
    elif len(pin) >= 6:
        skor += 5

    # Penalti digit bersebelahan selisih 1 -> -5 poin
    for i in range(len(pin) - 1):
        if pin[i] in "0123456789" and pin[i+1] in "0123456789":
            selisih = int(pin[i]) - int(pin[i+1])
            if selisih == 1 or selisih == -1:
                skor -= 5

    return skor

def kategori(skor):
    if skor >= 40: return "Kuat"
    if skor >= 20: return "Sedang"
    return "Lemah"

# Program Utama
n = int(input("Masukkan jumlah kandidat PIN (N): "))
kuat = sedang = lemah = 0

for i in range(1, n + 1):
    pin = input(f"Kandidat PIN ke-{i}: ")
    s = hitung_skor(pin)
    k = kategori(s)
    print(f"PIN ke-{i} skornya {s}, tergolong {k}.")

    if k == "Kuat": kuat += 1
    elif k == "Sedang": sedang += 1
    else: lemah += 1

print(f"Rekap: Kuat {kuat}, Sedang {sedang}, Lemah {lemah}")
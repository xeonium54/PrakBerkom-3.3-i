# Deskripsi : Menyederhanakan aspect ratio foto menggunakan FPB

# Fungsi untuk menghitung FPB
def FPB(a, b):
  while b != 0:
    r = a % b
    a = b
    b = r

  return a

lebar = int(input("Masukkan lebar foto ( piksel ): "))
tinggi = int(input("Masukkan tinggi foto ( piksel ): "))

hasil = FPB(lebar, tinggi)

lebar_baru = lebar // hasil
tinggi_baru = tinggi // hasil

print("Aspect ratio disederhanakan menjadi",
      str(lebar_baru) + ":" + str(tinggi_baru))
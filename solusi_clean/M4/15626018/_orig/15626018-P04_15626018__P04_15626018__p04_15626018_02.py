def hitung_skor(pin):
  skor = 0
  angka = ""

  for i in range(len(pin)):
    if pin[i] >= "0" and pin[i] <= "9":
      if pin[i] not in angka:
        angka = angka + pin[i]

  skor = skor + len(angka) * 4

  for i in range (len(pin)):
    if pin[i] >= "A" and pin[i] <= "Z":
      skor = skor + 10
      break

  if len(pin) >= 8:
    skor = skor + 15
  elif len(pin) >= 6:
    skor = skor + 5

  for i in range (len(pin) - 1):
    if pin[i] >= "0" and pin[i] <= "9":
      if pin [i+1] >= "0" and pin[i+1] <= "9":
        a = int(pin[i])
        b = int(pin[i+1])

        if a - b == 1 or b - a == 1:
          skor = skor - 5

  return skor

def kategori(skor):
  if skor >= 40:
    return "Kuat"
  elif skor >= 20:
    return "Sedang"
  else:
    return "Lemah"

N = int(input("Masukkan jumlah kandidat PIN (N): "))

kuat = 0
sedang = 0
lemah = 0

for i in range(1, N + 1):
  pin = input("Kandidat PIN ke-" + str(i) + ": ")

  skor = hitung_skor(pin)
  hasil = kategori(skor)

  print("PIN ke-" + str(i) + " skornya " + str(skor) + ", tergolong " + hasil + ".")

  if hasil == "Kuat":
    kuat = kuat + 1
  elif hasil == "Sedang":
    sedang = sedang + 1
  else:
    lemah = lemah + 1

print("Rekap : Kuat " + str(kuat) + ", Sedang " + str(sedang) + ", Lemah " + str(lemah))
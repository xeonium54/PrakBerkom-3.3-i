def belajar(modul, lama, waktu, energi, total):
  if lama > waktu:
    lama = waktu

  if lama * 5 > energi:
    lama = energi / 5

  total[modul-1] = total[modul-1] + lama
  waktu = waktu - lama
  energi = energi - lama * 5

  return waktu, energi, total

def tidur(waktu, energi):
  energi = energi + waktu * 12.5

  if energi > 100:
    energi = 100

  waktu = 0

  return waktu, energi
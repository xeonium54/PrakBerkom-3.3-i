def hitung_FPB(a, b):
    if b == 0:
        return a
    else:
        return hitung_FPB(b, a % b)

lebar_awal = int(input("LEBAR DALAM PX: "))
tinggi_awal = int(input("TINGGI DALAM PX: "))

FPB_Foto = hitung_FPB(lebar_awal, tinggi_awal)

lebar_akhir = lebar_awal // FPB_Foto
tinggi_akhir = tinggi_awal // FPB_Foto

print(f"rasio foto menjadi {lebar_akhir} : {tinggi_akhir}")

